"""Write briefing notes back to Linear as internal comments."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from src.core.briefing.models import Briefing
from src.integrations.linear.client import LinearClient

# Embedded in every comment we post so we can detect our own notes.
_MARKER_PREFIX = "<!-- support-buddy briefing:"
_MARKER_SUFFIX = " -->"


def _marker(briefing_id: str) -> str:
    return f"{_MARKER_PREFIX}{briefing_id}{_MARKER_SUFFIX}"


def _format_note(briefing: Briefing) -> str:
    lines: list[str] = [
        "## Support Buddy Briefing",
        "",
        f"**Summary:** {briefing.summary}",
        f"**Severity:** {briefing.effective_severity.value}  |  "
        f"**Category:** {briefing.category.value}  |  "
        f"**Routing:** {briefing.autonomy.value}",
    ]

    if briefing.autonomy_reasons:
        lines += ["", "**Routing reasons:**"]
        lines += [f"- {r}" for r in briefing.autonomy_reasons]

    if briefing.citations:
        lines += ["", "**KB references:**"]
        lines += [f"- {c.title}" for c in briefing.citations]

    failed = [c for c in briefing.checks if not c.passed]
    if failed:
        lines += ["", "**Failed checks:**"]
        lines += [f"- `{c.name}`: {c.detail}" for c in failed]

    if briefing.draft_body:
        lines += ["", "**Draft reply:**", "", briefing.draft_body]
    else:
        lines += ["", "_No draft available._"]

    lines += ["", "---", f"_Generated by Support Buddy · score {briefing.verification_score:.2f}_"]
    lines += [_marker(briefing.id)]

    return "\n".join(lines)


@dataclass
class WriteBackResult:
    dry_run: bool
    already_posted: bool = False
    comment_id: str | None = None
    preview: str | None = None
    label_applied: bool = False


class LinearWriteBack:
    """Posts briefing notes to Linear issues and reads sent replies for edit-ratio tracking."""

    def __init__(self, client: LinearClient) -> None:
        self._client = client
        self._viewer_id: str | None = None

    def _get_viewer_id(self) -> str:
        if self._viewer_id is None:
            self._viewer_id = self._client.get_viewer()["id"]
        return self._viewer_id

    def _already_posted(self, issue_id: str, briefing_id: str) -> bool:
        marker = _marker(briefing_id)
        return any(marker in c["body"] for c in self._client.get_comments(issue_id))

    def post_briefing_note(
        self,
        issue_id: str,
        briefing: Briefing,
        dry_run: bool = True,
    ) -> WriteBackResult:
        """Post a briefing summary as a comment on *issue_id*.

        Does nothing and returns ``already_posted=True`` when a comment for
        this briefing is already present (idempotent / loop-safe).
        Dry-run by default: pass ``dry_run=False`` to actually write.
        """
        if self._already_posted(issue_id, briefing.id):
            return WriteBackResult(dry_run=dry_run, already_posted=True)

        body = _format_note(briefing)

        if dry_run:
            return WriteBackResult(dry_run=True, preview=body)

        comment_id = self._client.add_comment(issue_id, body)
        return WriteBackResult(dry_run=False, comment_id=comment_id, preview=body)

    def ensure_label(
        self,
        issue_id: str,
        team_id: str = "",
        label_name: str = "ai-briefed",
        dry_run: bool = True,
    ) -> WriteBackResult:
        """Find-or-create *label_name* and apply it to *issue_id*.

        Dry-run by default.
        """
        if dry_run:
            return WriteBackResult(dry_run=True, label_applied=False)

        existing = {lb["name"]: lb["id"] for lb in self._client.list_labels(team_id)}
        if label_name in existing:
            label_id = existing[label_name]
        else:
            label_id = self._client.create_label(team_id, label_name)

        self._client.add_label_to_issue(issue_id, label_id)
        return WriteBackResult(dry_run=False, label_applied=True)

    def fetch_sent_reply(self, issue_id: str) -> dict[str, Any] | None:
        """Return the latest non-bot comment, or None if the TSE hasn't replied yet."""
        bot_id = self._get_viewer_id()
        comments = self._client.get_comments(issue_id)
        human = [c for c in comments if c.get("user_id") != bot_id]
        return human[-1] if human else None
